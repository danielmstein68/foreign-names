"""Step 4: CHECKPOINT report, before any regression.

Reports (a) how many candidates got name scores and who was dropped, and
(b) how whiteness and foreignness combine: how many candidates are in each
high/low cell, per source. Stop here and wait for Daniel's approval.

This script deliberately never reads vote_share, votes or winner.

Output: output/04_checkpoint.md
Run:  .venv/bin/python src/04_checkpoint.py
"""

import pandas as pd

from common import OUTPUT, PROCESSED

# Columns this script may use. Anything about votes or winning is left out on
# purpose, so the checkpoint cannot be influenced by results.
COLUMNS = ["source", "office", "year", "state", "contest_id", "surname", "nonpartisan", "incumbent",
           "uncontested", "multiseat", "census_match_rule", "census_matched", "eth_abstained", "fully_scored",
           "nonwhite", "foreign", "foreign_alt", "foreign_top"]

MIN_CELL = 200  # flag cells with fewer candidates than this as too small to estimate well


def md(df: pd.DataFrame) -> str:
    """DataFrame -> Markdown table."""
    return df.to_markdown()


def sample_label(row) -> str:
    if row["source"] == "local":
        return "Local nonpartisan" if row["nonpartisan"] else "Local partisan"
    return {"house": "House", "senate": "Senate"}[row["source"]]


def main() -> None:
    df = pd.read_parquet(PROCESSED / "candidates_scored.parquet", columns=COLUMNS)
    df["sample"] = df.apply(sample_label, axis=1)
    df["decade"] = (df["year"] // 10 * 10).astype(str) + "s"
    main_sample = df[~df["uncontested"] & ~df["multiseat"]]
    out = ["# Checkpoint report", "",
           "Generated by `src/04_checkpoint.py`. No vote shares or election results were used.", ""]

    # ---- (a) Match rates -------------------------------------------------
    out += ["## (a) Match rates", "",
            "Main sample = contested, single-seat races, which are the races the regressions will use.", ""]
    rates = main_sample.groupby("sample").agg(
        candidates=("contest_id", "size"),
        census_full_match=("census_match_rule", lambda s: (s == "full").mean()),
        census_part_match=("census_match_rule", lambda s: s.isin(["first_part", "last_part"]).mean()),
        census_unmatched=("census_matched", lambda s: 1 - s.mean()),
        ethnicolr_abstained=("eth_abstained", lambda s: s.fillna(True).mean()),
        fully_scored=("fully_scored", "mean"))
    out += [md(rates.round(3)), ""]

    # Contests lose candidates when a name is unscored; a contest needs 2+ scored candidates to count.
    scored_per_contest = main_sample.groupby(["sample", "contest_id"])["fully_scored"].sum()
    usable = scored_per_contest.ge(2).groupby("sample").agg(["size", "sum"])
    usable.columns = ["contests", "contests_with_2plus_scored"]
    usable["share_usable"] = usable["contests_with_2plus_scored"] / usable["contests"]
    out += ["Contests still usable after dropping unscored candidates (they need at least 2 scored candidates):", "",
            md(usable.round(3)), ""]

    # ---- Who is dropped? -------------------------------------------------
    out += ["### Who is dropped (unscored vs scored candidates, main sample)", ""]
    ms = main_sample.assign(status=main_sample["fully_scored"].map({True: "kept", False: "dropped"}))
    by_decade = pd.crosstab(ms["decade"], ms["status"], normalize="columns").round(3)
    by_office = pd.crosstab(ms["office"], ms["status"], normalize="columns").round(3)
    drop_rate_office = ms.groupby("office")["fully_scored"].apply(lambda s: 1 - s.mean()).round(3).rename("drop_rate")
    by_state = ms.groupby("state")["fully_scored"].agg(n="size", drop_rate=lambda s: 1 - s.mean())
    by_state = by_state[by_state["n"] >= 200].sort_values("drop_rate", ascending=False).round(3)
    inc = ms.groupby("status")["incumbent"].mean().round(3).rename("share_incumbent")
    out += ["**By decade** (each column sums to 1):", "", md(by_decade), "",
            "**By office** (each column sums to 1), and the drop rate within each office:", "",
            md(by_office.join(drop_rate_office)), "",
            "**States with the highest drop rates** (states with at least 200 candidates):", "",
            md(by_state.head(8)), "",
            "**States with the lowest drop rates:**", "", md(by_state.tail(5)), "",
            "**Share incumbent, dropped vs kept:**", "", md(inc.to_frame()), "",
            "**Most common unmatched surnames:**", "",
            ", ".join(ms.loc[~ms["census_matched"], "surname"].value_counts().head(30).index), ""]

    # ---- (b) Joint distribution -------------------------------------------
    sc = main_sample[main_sample["fully_scored"]].copy()
    nw_cut = sc["nonwhite"].quantile([1 / 3, 2 / 3])
    fo_cut = sc["foreign"].quantile([1 / 3, 2 / 3])
    sc["nonwhite_t"] = pd.cut(sc["nonwhite"], [-0.01, nw_cut.iloc[0], nw_cut.iloc[1], 1.01], labels=["low", "mid", "high"])
    sc["foreign_t"] = pd.cut(sc["foreign"], [-0.01, fo_cut.iloc[0], fo_cut.iloc[1], 1.01], labels=["low", "mid", "high"])
    sc["nw_hi"] = sc["nonwhite_t"] == "high"
    sc["fo_hi"] = sc["foreign_t"] == "high"
    sc["cell"] = sc["nw_hi"].map({True: "non-white", False: "white"}) + " / " + \
        sc["fo_hi"].map({True: "foreign", False: "not foreign"})

    out += ["## (b) Whiteness × foreignness", "",
            "Terciles are computed on the pooled main sample (all sources), as fixed in "
            "`docs/foreign_coding_rule.md`.",
            f"- **Non-white tercile cut-offs:** {nw_cut.iloc[0]:.3f} and {nw_cut.iloc[1]:.3f}. "
            f"\"High\" means the surname is more than {nw_cut.iloc[1]:.0%} non-white in the Census.",
            f"- **Foreign tercile cut-offs:** {fo_cut.iloc[0]:.3f} and {fo_cut.iloc[1]:.3f}. "
            f"\"High\" means P(not British) is above {fo_cut.iloc[1]:.2f}.", "",
            "### 2 × 2 cells: top tercile vs the rest", ""]

    cells = pd.crosstab(sc["sample"], sc["cell"])
    cells["total"] = cells.sum(axis=1)
    out += ["Candidates per cell:", "", md(cells), ""]

    # Within-contest variation is what the fixed-effects model actually uses.
    def contests_with_variation(col):
        v = sc.groupby(["sample", "contest_id"])[col].nunique().gt(1)
        return v.groupby("sample").sum()
    var = pd.DataFrame({"contests_varying_in_nonwhite_cell": contests_with_variation("nw_hi"),
                        "contests_varying_in_foreign_cell": contests_with_variation("fo_hi"),
                        "contests_varying_in_2x2_cell": contests_with_variation("cell")})
    out += ["Contests where candidates fall in **different** cells. Only these contests tell the fixed-effects "
            "model anything about names:", "", md(var), ""]

    small = [(s, c, n) for s in cells.index for c in cells.columns[:-1] if (n := cells.loc[s, c]) < MIN_CELL]
    if small:
        out += [f"**Cells with fewer than {MIN_CELL} candidates (too small to estimate reliably):**", ""]
        out += [f"- {s}, {c}: {n} candidates" for s, c, n in small] + [""]
    else:
        out += [f"No cell has fewer than {MIN_CELL} candidates.", ""]

    out += ["### Most common surnames in each cell (pooled)", ""]
    for c in sorted(sc["cell"].unique()):
        names = sc.loc[sc["cell"] == c, "surname"].value_counts().head(15).index
        out += [f"- **{c}:** " + ", ".join(names)]
    out += [""]

    out += ["### Full 3 × 3 tercile table (rows = non-white tercile, columns = foreign tercile)", ""]
    for s in ["Local nonpartisan", "Local partisan", "House", "Senate"]:
        t = pd.crosstab(sc.loc[sc["sample"] == s, "nonwhite_t"], sc.loc[sc["sample"] == s, "foreign_t"])
        out += [f"**{s}**", "", md(t), ""]

    out += ["### Sensitivity: the same 2 × 2 using the binary foreign score (most likely origin ≠ British)", ""]
    sc["cell_bin"] = sc["nw_hi"].map({True: "non-white", False: "white"}) + " / " + \
        sc["foreign_top"].map({1: "foreign", 0: "not foreign"})
    out += [md(pd.crosstab(sc["sample"], sc["cell_bin"])), ""]

    out += ["### Correlation between the two scores (main sample)", "",
            md(sc.groupby("sample")[["nonwhite", "foreign"]].corr().xs("foreign", level=1)[["nonwhite"]]
               .rename(columns={"nonwhite": "corr(nonwhite, foreign)"}).round(3)), ""]

    OUTPUT.mkdir(exist_ok=True)
    (OUTPUT / "04_checkpoint.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
